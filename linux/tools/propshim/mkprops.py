#!/usr/bin/env python3
"""props.h for propshim.c from a captured `getprop` dump ([key]: [value] lines).

Usage: mkprops.py <props.txt> <props.h>
Skips init.svc*/ro.boottime* (process state, meaningless off Android). Overrides below win.
"""
import re
import sys

OVERRIDES = {
    # wmt_launcher polls this until wmt_loader (run WITHOUT the shim) has set the chip up
    "vendor.connsys.driver.ready": "yes",
}
SKIP = re.compile(r"^(init\.svc|init\.svc_debug_pid|ro\.boottime)\.")


def cstr(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    src, dst = sys.argv[1], sys.argv[2]
    props = {}
    for line in open(src, encoding="utf-8", errors="replace"):
        m = re.match(r"^\[([^\]]+)\]: \[(.*)\]$", line.rstrip("\n"))
        if m and not SKIP.match(m.group(1)):
            props[m.group(1)] = m.group(2)
    props.update(OVERRIDES)
    for k, v in props.items():
        if len(v) > 91:
            raise SystemExit(f"value too long for PROP_VALUE_MAX: {k}")
    with open(dst, "w") as f:
        f.write("/* generated by mkprops.py from %s */\nstatic const struct kv PROPS[] = {\n" % src.split("/")[-1])
        for k in sorted(props):
            f.write("    { %s, %s },\n" % (cstr(k), cstr(props[k])))
        f.write("};\n")
    print(f"{len(props)} properties -> {dst}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
